  /* Cada parell genera 2 preguntes (en els dos sentits) amb distractors
     deterministes (índex fix) perquè no hi hagi dues preguntes iguals. */
  function buildPairs(pairs, category, template) {
    const words = [];
    pairs.forEach(p => { words.push(p[0], p[1]); });
    const out = [];
    const seen = new Set();
    pairs.forEach((p, i) => {
      [[p[0], p[1]], [p[1], p[0]]].forEach(pair => {
        const w = pair[0], ans = pair[1];
        const text = template(w);
        if (seen.has(text)) return;   // evita preguntes repetides
        seen.add(text);
        const pool = words.filter(x => x !== w && x !== ans);
        const d1 = pool[(i * 7 + 3) % pool.length];
        let idx = (i * 13 + 11) % pool.length, d2 = pool[idx], g = 0;
        while (d2 === d1 && g < pool.length) { idx = (idx + 1) % pool.length; d2 = pool[idx]; g++; }
        out.push({
          category,
          text,
          options: [ans, d1, d2],
          correct: 0
        });
      });
    });
    return out;
  }

